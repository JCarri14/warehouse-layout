import { test, expect } from '@playwright/test'

test('filtros de elementos combinan tipo y texto sin cambiar selección o plano', async ({ page }) => {
 await page.goto('/app')
 await page.getByRole('button', {name:'Abrir ejemplo detallado',exact:true}).click()
 const rows=page.locator('.element-row')
 await expect(rows).toHaveCount(26)
 await rows.filter({hasText:'D2'}).click()
 const canvas=page.locator('.canvas-panel canvas')
 await expect(canvas).toBeVisible()
 await canvas.evaluate(element => { element.setAttribute('data-retained','yes') })
 await page.getByLabel('Mostrar elementos',{exact:true}).selectOption('zone')
 await expect(rows).toHaveCount(3)
 await expect(page.getByText('La selección está fuera del filtro.',{exact:true})).toBeVisible()
 await expect(canvas).toHaveAttribute('data-retained','yes')
 await page.getByLabel('Buscar elementos',{exact:true}).fill('recepcion')
 await expect(rows).toHaveCount(1)
 await expect(rows).toContainText('Recepción')
 await page.getByLabel('Buscar elementos',{exact:true}).fill('inexistente')
 await expect(rows).toHaveCount(0)
 await expect(page.getByText('No hay elementos que coincidan con los filtros.')).toBeVisible()
 await page.getByRole('button',{name:'Mostrar todos',exact:true}).click()
 await expect(rows).toHaveCount(26)
 await expect(page.locator('.element-row.active')).toContainText('D2')
 await page.getByLabel('Buscar elementos',{exact:true}).fill('d2')
 await expect(rows).toHaveCount(1)
 await page.getByRole('button',{name:'Ajustes',exact:true}).click()
 await page.getByLabel('Idioma',{exact:true}).selectOption('en')
 await page.getByRole('button',{name:'Settings',exact:true}).click()
 await expect(page.getByLabel('Search elements',{exact:true})).toHaveValue('d2')
 await page.getByRole('button',{name:'Show all',exact:true}).click()
 await page.setViewportSize({width:1100,height:740})
 await expect(page.getByLabel('Show elements',{exact:true})).toBeInViewport()
 await page.screenshot({path:'artifacts/element-filters.png'})
})
