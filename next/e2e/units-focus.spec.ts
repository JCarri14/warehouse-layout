  await expect(page.locator('.order-table tbody tr')).toHaveCount(2)
  await page.mouse.click(orderPoint.x, orderPoint.y)
  await expect(page.locator('.order-table tbody tr[aria-selected=true]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Recorridos', exact: true }).click()
  await page.getByRole('button', { name: 'Calcular ruta', exact: true }).click()
  await expect(page.locator('.route-results')).toBeVisible({ timeout: 30000 })
  await page.screenshot({ path: 'artifacts/recorrido-visible-superior.png' })
  await page.getByRole('button', { name: 'Isométrica', exact: true }).click()
