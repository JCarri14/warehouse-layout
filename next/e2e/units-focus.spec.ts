  await page.getByLabel('Cantidad para REF-1 · A10101').fill('2,5')
  await page.getByLabel('Cantidad para REF-2 · B10102').fill('3')
  await page.screenshot({ path: 'artifacts/inventario-preparar-orden.png' })
