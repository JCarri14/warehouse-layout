import { warehouseAction } from './helpers'
import { test } from './fixtures'
import { expect, type Page } from '@playwright/test'
import fs from 'node:fs/promises'
async function exported(page: Page) {
  const event = page.waitForEvent('download')
  await warehouseAction(page, 'Guardar almacén')
  return JSON.parse(await fs.readFile((await (await event).path())!, 'utf8'))
}
test('configura el formato y localiza ubicaciones sin modificar los datos', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/app')
  await page.getByRole('tab', { name: 'Ubicaciones', exact: true }).click()
  await page.getByLabel('Formato de ubicación', { exact: true }).fill('{S}-{N}-{C}')
  await expect(page.locator('.template-feedback')).toContainText('A5-01-10')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await page.getByRole('button', { name: 'Añadir estantería', exact: true }).first().click()
  await page.getByRole('tab', { name: 'Ubicaciones', exact: true }).click()
  await page.getByLabel('Nivel de vista previa').selectOption({ label: '01 · 1,4 m' })
  await expect(page.getByRole('button', { name: 'Mostrar A0-01-02', exact: true })).toBeVisible()
  const before = await exported(page)
  await page.getByRole('button', { name: 'Mostrar A0-01-02', exact: true }).click()
  await expect(page.locator('.location-focus-summary')).toContainText('A0-01-02')
  await page.getByRole('textbox', { name: 'Código de ubicación', exact: true }).fill(' a0-1-2 ')
  await page.getByRole('button', { name: 'Localizar', exact: true }).click()
  await expect(page.locator('.location-focus-summary')).toContainText('Nivel 01 · Columna 02')
  expect(await exported(page)).toEqual(before)
  await page.screenshot({ path: 'artifacts/editor-ubicacion-isometrica.png' })
  await page.getByRole('button', { name: 'Superior', exact: true }).click()
  await page.setViewportSize({ width: 1100, height: 740 })
  await page.screenshot({ path: 'artifacts/editor-ubicacion-superior.png' })
  expect(errors).toEqual([])
})
test('rechaza formatos inválidos y deshace los cambios de formato', async ({ page }) => {
  await page.goto('/app')
  await page.getByRole('tab', { name: 'Ubicaciones', exact: true }).click()
  await page.getByLabel('Formato de ubicación', { exact: true }).fill('{S}{C}')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('nivel')
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await page.getByRole('tab', { name: 'Ubicaciones', exact: true }).click()
  await page.getByLabel('Formato de ubicación', { exact: true }).fill('{C}/{S}/{N}')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  await page.getByRole('tab', { name: 'Ubicaciones', exact: true }).click()
  await expect(page.getByLabel('Formato de ubicación', { exact: true })).toHaveValue('{S}{N}{C}')
  await page.getByRole('button', { name: 'Rehacer', exact: true }).click()
  const doc = await exported(page)
  expect(doc.locationTemplate).toBe('{C}/{S}/{N}')
  await page.getByLabel('Abrir archivo de almacén').setInputFiles({ name: 'formato.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(doc)) })
  await page.getByRole('tab', { name: 'Ubicaciones', exact: true }).click()
  await expect(page.getByLabel('Formato de ubicación', { exact: true })).toHaveValue('{C}/{S}/{N}')
})
test('comprueba la existencia real de nivel y columna y protege las propiedades pendientes', async ({ page }) => {
  await page.goto('/app')
  await page.getByRole('button', { name: 'Añadir estantería', exact: true }).first().click()
  await page.getByRole('textbox', { name: 'Código de ubicación', exact: true }).fill('A09901')
  await page.getByRole('button', { name: 'Localizar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('nivel')
  await page.getByRole('textbox', { name: 'Código de ubicación', exact: true }).fill('A00199')
  await page.getByRole('button', { name: 'Localizar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('columna')
  await page.getByLabel('Nombre opcional').fill('Sin aplicar')
  await page.getByRole('textbox', { name: 'Código de ubicación', exact: true }).fill('A00102')
  await page.getByRole('button', { name: 'Localizar', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Propiedades sin aplicar')
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Nombre opcional')).toHaveValue('Sin aplicar')
})

