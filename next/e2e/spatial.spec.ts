import { warehouseAction } from './helpers'
import { expect, type Page } from '@playwright/test'
import { test } from './fixtures'
import fs from 'node:fs/promises'
async function exported(page: Page) {
  const event = page.waitForEvent('download')
  await warehouseAction(page, 'Guardar almacén')
  return JSON.parse(await fs.readFile((await (await event).path())!, 'utf8'))
}
test('crear, editar y reabrir zonas, obstáculos y mesas', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/app')
  await page.getByRole('button', { name: 'Añadir zona', exact: true }).click()
  await page.getByLabel('Nombre de zona', { exact: true }).fill('Preparación')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await page.getByRole('button', { name: 'Añadir estantería', exact: true }).first().click()
  await page.getByRole('button', { name: 'Añadir obstáculo', exact: true }).click()
  await page.getByLabel('Nombre del elemento', { exact: true }).fill('Pilar norte')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await page.getByRole('button', { name: 'Añadir mesa', exact: true }).click()
  await page.getByLabel('Coordenada X').fill('7,5'); await page.getByLabel('Coordenada Y').fill('29')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  const doc = await exported(page)
  expect(doc.version).toBe(4); expect(doc.zones[0].name).toBe('Preparación')
  expect(doc.fixtures.map((f: { kind: string }) => f.kind)).toEqual(['obstacle', 'table'])
  expect(doc.racks).toHaveLength(1)
  await page.getByLabel('Abrir archivo de almacén').setInputFiles({ name: 'completo.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(doc)) })
  expect(await exported(page)).toEqual(doc)
  await expect(page.locator('.element-row')).toHaveCount(4)
  await page.locator('.element-row[data-kind=table]').click()
  await page.screenshot({ path: 'artifacts/editor-elementos-isometrico.png' })
  await page.setViewportSize({ width: 1100, height: 740 })
  await page.screenshot({ path: 'artifacts/editor-elementos-portatil.png' })
  expect(errors).toEqual([])
})
