test('mover una zona no mueve su contenido y sigue siendo posible seleccionar la estantería', async ({ page }) => {
  await page.goto('/app')
  await page.getByRole('button', { name: 'Añadir zona', exact: true }).click()
  await page.getByRole('button', { name: 'Añadir estantería', exact: true }).first().click()
  await page.getByRole('button', { name: 'Superior', exact: true }).click()
  const before = await exported(page)
  const b = (await page.locator('.viewport canvas').boundingBox())!
  const half = Math.max(17 * 1.15 + 2, (16 * 1.15 + 2) / (b.width / b.height)), s = b.height / (2 * half)
  const p = (x: number, y: number) => ({ x: b.x + b.width / 2 + (x - 16) * s, y: b.y + b.height / 2 + (y - 17) * s })
  const start = p(2, 4), end = p(12, 14)
  await page.mouse.move(start.x, start.y); await page.mouse.down(); await page.mouse.move(end.x, end.y, { steps: 8 }); await page.mouse.up()
  const moved = await exported(page)
  expect(moved.zones[0]).toMatchObject({ xMm: 11000, yMm: 11000 })
  expect(moved.racks).toEqual(before.racks)
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  const rack = p(4, 1.6); await page.mouse.click(rack.x, rack.y)
  await expect(page.getByLabel('Código', { exact: true })).toHaveValue('A0')
})

