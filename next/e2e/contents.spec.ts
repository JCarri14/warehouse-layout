import { changeLanguage } from './helpers'
import { test } from './fixtures'
import { expect, type Page } from '@playwright/test'
import fs from 'node:fs/promises'
import { warehouseAction } from './helpers'
async function exported(page: Page) {
  const event = page.waitForEvent('download')
  await warehouseAction(page, 'Guardar almacén')
  return JSON.parse(await fs.readFile((await (await event).path())!, 'utf8'))
}

test('palets y gavetas por estantería: aplicar, cancelar, historial, archivo y recuperación', async ({ page }) => {
  test.setTimeout(60000)
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/app')
  await page.getByRole('button', { name: 'Añadir estantería', exact: true }).first().click()
  const original = await exported(page)
  const contents = page.getByLabel('Contenido ilustrativo', { exact: true })
  await expect(contents).toHaveValue('shelves')
  await page.getByRole('tab', { name: 'General', exact: true }).click()
  await contents.selectOption('bins')
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(contents).toHaveValue('shelves')
  await page.getByRole('tab', { name: 'General', exact: true }).click()
  await contents.selectOption('pallets')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByLabel('Representación del almacén', { exact: true })).toHaveValue('detailed')
  const pallets = await exported(page)
  expect(pallets.racks[0].contents).toBe('pallets')
  expect(pallets.racks[0].levels).toEqual(original.racks[0].levels)
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  await expect(contents).toHaveValue('shelves')
  await page.getByRole('button', { name: 'Rehacer', exact: true }).click()
  await expect(contents).toHaveValue('pallets')
  await page.getByLabel('Código de ubicación', { exact: true }).fill('A00101')
  await page.getByRole('button', { name: 'Localizar', exact: true }).click()
  await page.screenshot({ path: 'artifacts/estanteria-palets-cajas.png' })
  await page.getByRole('tab', { name: 'General', exact: true }).click()
  await contents.selectOption('bins')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await page.screenshot({ path: 'artifacts/estanteria-gavetas.png' })
  await page.getByRole('tab', { name: 'General', exact: true }).click()
  await contents.selectOption('cartons')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await page.screenshot({ path: 'artifacts/estanteria-carton.png' })
  const cartons = await exported(page)
  expect(cartons.racks[0].contents).toBe('cartons')
  expect(cartons.racks[0].levels).toEqual(original.racks[0].levels)
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  const bins = await exported(page)
  expect(bins.racks[0].contents).toBe('bins')
  expect(bins.racks[0].levels).toEqual(original.racks[0].levels)
  await page.getByRole('button', { name: 'Superior', exact: true }).click()
  await page.getByRole('button', { name: 'Duplicar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Superior', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Deshacer', exact: true }).click()
  await warehouseAction(page, 'Nuevo almacén')
  await page.getByLabel('Abrir archivo de almacén', { exact: true }).setInputFiles({ name: 'gavetas.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(bins)) })
  await page.locator('.element-row').first().click()
  await expect(contents).toHaveValue('bins')
  await page.getByRole('tab', { name: 'General', exact: true }).click()
  await contents.selectOption('pallets')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('optiruta.workspace.recovery.v1') || '{}').session?.pendingEdit?.values.contents)).toBe('pallets')
  page.on('dialog', dialog => dialog.accept()); await page.reload()
  await page.getByRole('button', { name: 'Recuperar sesión', exact: true }).click()
  await expect(contents).toHaveValue('pallets')
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(contents).toHaveValue('bins')
  await changeLanguage(page, 'en')
  await expect(page.getByLabel('Illustrative contents', { exact: true })).toHaveValue('bins')
  await expect(page.getByText('Illustrative view; does not indicate real stock.', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('abre la copia del ejemplo detallado sin reemplazar cambios hasta confirmar', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/app')
  await page.getByLabel('Nombre del almacén', { exact: true }).fill('Trabajo propio')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await page.getByRole('button', { name: 'Inventario', exact: true }).click()
  await warehouseAction(page, 'Abrir ejemplo detallado')
  await expect(page.getByRole('dialog')).toContainText('Guardar el almacén actual')
  await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Inventario', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('Nombre del almacén', { exact: true })).toHaveValue('Trabajo propio')
  await expect(page.getByLabel('Representación del almacén', { exact: true })).toHaveValue('blocks')
  await warehouseAction(page, 'Abrir ejemplo detallado')
  await page.getByRole('button', { name: 'Descartar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Diseñar', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.element-row')).toHaveCount(26)
  await expect(page.getByLabel('Representación del almacén', { exact: true })).toHaveValue('detailed')
  const doc = await exported(page)
  expect(doc.racks).toHaveLength(22); expect(doc.zones).toHaveLength(3)
  await page.screenshot({ path: 'artifacts/ejemplo-detallado-escritorio-web.png' })
  await page.getByRole('complementary', { name: 'Elementos del almacén', exact: true }).getByRole('button', { name: /^D6 / }).click()
  await expect(page.getByLabel('Contenido ilustrativo', { exact: true })).toHaveValue('bins')
  await expect(page.getByLabel('Altura real (opcional)', { exact: true })).toHaveValue('')
  await page.getByRole('tab', { name: 'Ubicaciones', exact: true }).click()
  await expect(page.getByLabel('Columnas', { exact: true })).toHaveValue('10')
  await changeLanguage(page, 'en')
  await page.getByRole('tab', { name: 'General', exact: true }).click()
  await page.getByLabel('Illustrative contents', { exact: true }).selectOption('cartons')
  await page.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(page.getByLabel('Illustrative contents', { exact: true })).toHaveValue('cartons')
  expect(errors).toEqual([])
})

