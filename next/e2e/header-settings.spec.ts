import { test } from './fixtures'
import { expect } from '@playwright/test'

test('la marca sustituye Inicio y conserva navegación por teclado y borradores', async ({ page }) => {
  await page.goto('/app')
  const home = page.getByRole('button', { name: 'Ir a Inicio', exact: true })
  await expect(page.locator('.home-navigation')).toHaveCount(0)
  await expect(home).toHaveAttribute('title', 'Ir a Inicio')
  await expect(home).not.toHaveAttribute('aria-current')
  const title = page.locator('.document-title')
  expect((await home.boundingBox())!.x).toBeLessThan((await title.boundingBox())!.x)
  await expect(page.getByLabel('Idioma', { exact: true })).toBeHidden()
  await page.getByLabel('Nombre del almacén').fill('Borrador de cabecera')
  await page.getByRole('button', { name: 'Ajustes', exact: true }).click()
  await expect(page.getByLabel('Unidad de medida')).toBeDisabled()
  await expect(page.getByLabel('Al iniciar', { exact: true })).toBeVisible()
  await page.getByLabel('Idioma', { exact: true }).selectOption('en')
  await expect(page.getByRole('button', { name: 'Settings', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByLabel('Warehouse name')).toHaveValue('Borrador de cabecera')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Settings', exact: true })).toBeFocused()
  const englishHome = page.getByRole('button', { name: 'Go to Home', exact: true })
  await englishHome.focus()
  await expect(englishHome).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Your warehouses' })).toBeVisible()
  await expect(englishHome).toHaveAttribute('aria-current', 'page')
  await expect(englishHome).toHaveAttribute('title', 'Go to Home')
  await page.getByRole('button', { name: 'Continue with the current plan' }).click()
  await expect(page.getByLabel('Warehouse name')).toHaveValue('Borrador de cabecera')
  await expect(englishHome).not.toHaveAttribute('aria-current')
  await page.getByRole('button', { name: 'Go to Home', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your warehouses' })).toBeVisible()
  await page.screenshot({ path: 'artifacts/cabecera-inicio.png' })
  await page.setViewportSize({ width: 1100, height: 740 })
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByLabel('Language', { exact: true })).toBeInViewport()
  await expect(page.getByLabel('On startup', { exact: true })).toBeInViewport()
  await page.screenshot({ path: 'artifacts/cabecera-ajustes-1100.png' })
  await page.getByRole('heading', { name: 'Your warehouses' }).click()
  await expect(page.getByLabel('Language', { exact: true })).toBeHidden()
})

