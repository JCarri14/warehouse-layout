import { test } from './fixtures'
import { expect, type Page } from '@playwright/test'

async function floorPoint(page: Page, x: number, y: number) {
  const box = (await page.locator('.operations-plan canvas').boundingBox())!
  const half = Math.max(34 / 2 * 1.15 + 2, (32 / 2 * 1.15 + 2) / (box.width / box.height)), scale = box.height / (2 * half)
  return { x: box.x + box.width / 2 + (x - 16) * scale, y: box.y + box.height / 2 + (y - 17) * scale }
}
test('previsualiza, cambia por clic y cancela sin mover el punto guardado', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/app')
  await page.getByRole('button', { name: 'Añadir estantería', exact: true }).first().click()
  await page.getByRole('button', { name: 'Recorridos', exact: true }).click()
  await page.getByText('Inicio, destino y precisión', { exact: true }).click()
  const initial = await page.getByLabel('Inicio · X', { exact: true }).inputValue()
  await page.getByRole('button', { name: 'Marcar inicio', exact: true }).click()
  await expect(page.locator('.is-placing-point')).toContainText('Selecciona la nueva casilla de inicio')
  const point = await floorPoint(page, 12.2, 12.2)
  await page.mouse.move(point.x, point.y)
  await expect(page.locator('.drag-status')).toContainText('Inicio provisional · X 12,5 m · Y 12,5 m')
  await expect(page.getByLabel('Inicio · X', { exact: true })).toHaveValue(initial)
  await page.screenshot({ path: 'artifacts/inicio-casilla-fantasma.png' })
  await page.mouse.click(point.x, point.y)
  await expect(page.getByLabel('Inicio · X', { exact: true })).toHaveValue('12,5')
  await expect(page.getByRole('button', { name: 'Cambiar inicio', exact: true })).toBeVisible()
  await expect(page.locator('.drag-status')).toHaveCount(0)
  await page.getByRole('button', { name: 'Cambiar inicio', exact: true }).click()
  const occupied = await floorPoint(page, 4.2, 1.6)
  await page.mouse.move(occupied.x, occupied.y)
  await expect(page.locator('.drag-status.invalid')).toContainText('casilla libre')
  await page.screenshot({ path: 'artifacts/inicio-casilla-bloqueada.png' })
  await page.mouse.click(occupied.x, occupied.y)
  await expect(page.getByRole('button', { name: 'Cambiar inicio', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('Inicio · X', { exact: true })).toHaveValue('12,5')
  const outside = await floorPoint(page, -1.2, 12.2)
  await page.mouse.move(outside.x, outside.y)
  await expect(page.locator('.drag-status.invalid')).toBeVisible()
  await page.mouse.click(outside.x, outside.y)
  await expect(page.getByLabel('Inicio · X', { exact: true })).toHaveValue('12,5')
  const replacement = await floorPoint(page, 18.2, 15.2)
  await page.mouse.click(replacement.x, replacement.y)
  await expect(page.getByLabel('Inicio · X', { exact: true })).toHaveValue('18,5')
  await expect(page.getByLabel('Inicio · Y', { exact: true })).toHaveValue('15,5')
  await page.getByRole('button', { name: 'Marcar destino', exact: true }).click()
  const end = await floorPoint(page, 22.2, 20.2)
  await page.mouse.click(end.x, end.y)
  await expect(page.getByLabel('Destino · X', { exact: true })).toHaveValue('22,5')
  await page.getByRole('button', { name: 'Cambiar destino', exact: true }).click()
  await page.mouse.move(replacement.x, replacement.y)
  await expect(page.locator('.drag-status')).toContainText('Destino provisional')
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Destino · X', { exact: true })).toHaveValue('22,5')
  await expect(page.locator('.drag-status')).toHaveCount(0)
  await expect(page.locator('.is-placing-point')).toHaveCount(0)
  const endMarker = await floorPoint(page, 22.5, 20.5), movedEnd = await floorPoint(page, 24.2, 23.2)
  await page.mouse.move(endMarker.x, endMarker.y); await page.mouse.down(); await page.mouse.move(movedEnd.x, movedEnd.y, { steps: 5 })
  await expect(page.locator('.drag-status')).toContainText('Destino provisional · X 24,5 m · Y 23,5 m')
  await expect(page.getByLabel('Destino · X', { exact: true })).toHaveValue('22,5')
  await page.screenshot({ path: 'artifacts/destino-arrastre-fantasma.png' })
  await page.keyboard.press('Escape'); await page.mouse.up()
  await expect(page.getByLabel('Destino · X', { exact: true })).toHaveValue('22,5')
  await page.mouse.move(endMarker.x, endMarker.y); await page.mouse.down(); await page.mouse.move(movedEnd.x, movedEnd.y, { steps: 5 }); await page.mouse.up()
  await expect(page.getByLabel('Destino · X', { exact: true })).toHaveValue('24,5')
  expect(errors).toEqual([])
})

test('conserva vista y zoom al volver a activar la colocación', async ({ page }) => {
  await page.goto('/app')
  await page.getByRole('button', { name: 'Recorridos', exact: true }).click()
  await page.getByRole('button', { name: 'Isométrica', exact: true }).click()
  await page.getByRole('button', { name: 'Marcar inicio', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Isométrica', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Superior', exact: true }).click()
  const box = (await page.locator('.operations-plan canvas').boundingBox())!
  const x = box.x + box.width * .63, y = box.y + box.height * .56
  await page.mouse.move(x, y); await page.mouse.wheel(0, -350)
  await page.getByRole('button', { name: 'Marcar inicio', exact: true }).click()
  await page.mouse.move(x, y)
  await expect(page.locator('.drag-status')).toContainText('Inicio provisional')
  const preview = await page.locator('.drag-status').innerText()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Marcar inicio', exact: true }).click()
  await page.mouse.move(x, y)
  await expect(page.locator('.drag-status')).toHaveText(preview)
})

