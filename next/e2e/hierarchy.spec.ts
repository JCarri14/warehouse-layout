import { test } from './fixtures'
import { expect } from '@playwright/test'
import { warehouseAction } from './helpers'

test('archivos bajo demanda, OT centrada en datos y plano plegable sin perder edición', async ({ page }) => {
  await page.goto('/app')
  const menu = page.getByRole('button', { name: 'Archivo del almacén' })
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await menu.click()
  await expect(page.getByRole('button', { name: 'Guardar almacén', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toBeFocused()
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await warehouseAction(page, 'Abrir ejemplo')
  await expect(menu).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: 'Órdenes de trabajo', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Importar OT', exact: true })).toHaveClass('primary')
  await page.getByLabel('Archivo de OT').setInputFiles({ name: 'OT-prueba.csv', mimeType: 'text/csv', buffer: Buffer.from('referencia;descripcion;ubicacion;cantidad\nREF-1182;Engranaje recto Z30;B20101;2\nREF-1266;Tornillo DIN 912 M8;B20103;3\n') })
  await page.getByRole('dialog').getByRole('button', { name: 'Importar OT', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Preparar recorrido →', exact: true })).toBeEnabled()
  await expect(page.locator('.order-summary')).toContainText('Lista para preparar el recorrido')
  await page.getByLabel('Cantidad línea 1').fill('2,5')
  await page.screenshot({ path: 'artifacts/jerarquia-ot-1440.png' })
  await page.getByRole('button', { name: 'Ocultar plano', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Plano de consulta' })).toBeHidden()
  await expect(page.getByLabel('Cantidad línea 1')).toHaveValue('2,5')
  await page.screenshot({ path: 'artifacts/jerarquia-ot-sin-plano-1440.png' })
  await page.getByRole('button', { name: 'Mostrar plano', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Plano de consulta' })).toBeVisible()
  await page.setViewportSize({ width: 1100, height: 740 })
  await page.screenshot({ path: 'artifacts/jerarquia-ot-1100.png' })
  await page.setViewportSize({ width: 760, height: 800 })
  await expect(page.getByRole('button', { name: 'Preparar recorrido →', exact: true })).toBeInViewport()
  await page.screenshot({ path: 'artifacts/jerarquia-ot-760.png' })
  await page.getByRole('button', { name: 'Preparar recorrido →', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Recorridos', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('Inicio · X', { exact: true })).toBeHidden()
  await page.getByText('Inicio, destino y precisión', { exact: true }).click()
  await expect(page.getByLabel('Inicio · X', { exact: true })).toBeVisible()
})

