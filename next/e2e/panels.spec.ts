import { test } from './fixtures'
import { expect, type Locator, type Page } from '@playwright/test'

async function width(panel: Locator) {
  return panel.evaluate(element => element.getBoundingClientRect().width)
}
async function dragSeparator(page: Page, separator: Locator, delta: number) {
  const box = await separator.boundingBox()
  if (!box) throw Error('No se encuentra el separador visible.')
  await page.mouse.move(box.x + box.width / 2, box.y + Math.min(100, box.height / 2))
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + delta, box.y + Math.min(100, box.height / 2), { steps: 8 })
  await page.mouse.up()
}

test('laterales de diseño ajustables con teclado, ratón, cancelación y persistencia', async ({ page }) => {
  await page.goto('/app')
  await expect(page.getByLabel('Paso de cuadrícula')).toHaveValue('-1')
  const left = page.getByRole('separator', { name: 'Ajustar panel de elementos', exact: true })
  const right = page.getByRole('separator', { name: 'Ajustar panel de propiedades', exact: true })
  await expect(left).toBeVisible(); await expect(right).toBeVisible()
  await expect(left).toHaveAttribute('aria-valuenow', '260')
  await left.focus(); await page.keyboard.press('ArrowRight')
  await expect(left).toHaveAttribute('aria-valuenow', '270')
  await dragSeparator(page, left, 80)
  await expect(left).toHaveAttribute('aria-valuenow', '350')
  await right.focus(); await page.keyboard.press('ArrowLeft')
  await expect(right).toHaveAttribute('aria-valuenow', '370')

  const before = await width(page.locator('.elements-panel'))
  const box = await left.boundingBox()
  if (!box) throw Error('Separador ausente.')
  await page.mouse.move(box.x + 3, box.y + 100); await page.mouse.down()
  await page.mouse.move(box.x + 63, box.y + 100, { steps: 5 })
  await page.keyboard.press('Escape'); await page.mouse.up()
  await expect.poll(() => width(page.locator('.elements-panel'))).toBeCloseTo(before, 0)
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('optiruta.panels.design')!).left)).toBe(350)
  await page.reload()
  await expect(left).toHaveAttribute('aria-valuenow', '350')
  await expect(right).toHaveAttribute('aria-valuenow', '370')
  await left.dblclick()
  await expect(left).toHaveAttribute('aria-valuenow', '260')
  await expect(right).toHaveAttribute('aria-valuenow', '360')
})

test('división por sección independiente y plegado sin perder la proporción', async ({ page }) => {
  await page.goto('/app')
  await page.getByRole('button', { name: 'Inventario', exact: true }).click()
  const separator = page.getByRole('separator', { name: 'Ajustar ancho de datos y plano', exact: true })
  await expect(separator).toHaveAttribute('aria-valuenow', '62')
  const before = await width(page.locator('.operations-data'))
  await dragSeparator(page, separator, 180)
  const inventoryWidth = await width(page.locator('.operations-data'))
  expect(inventoryWidth).toBeGreaterThan(before + 150)
  await page.getByRole('button', { name: 'Recorridos', exact: true }).click()
  await expect(separator).toHaveAttribute('aria-valuenow', '44')
  await dragSeparator(page, separator, -100)
  await page.getByRole('button', { name: 'Inventario', exact: true }).click()
  await expect.poll(() => width(page.locator('.operations-data'))).toBeCloseTo(inventoryWidth, 0)
  await page.getByRole('button', { name: 'Ocultar plano', exact: true }).click()
  await expect(separator).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Plano de consulta' })).toBeHidden()
  await expect.poll(() => width(page.locator('.operations-data'))).toBeGreaterThan(inventoryWidth)
  await page.getByRole('button', { name: 'Mostrar plano', exact: true }).click()
  await expect(separator).toBeVisible()
  await expect.poll(() => width(page.locator('.operations-data'))).toBeCloseTo(inventoryWidth, 0)
  await separator.focus(); await page.keyboard.press('Home')
  await expect(separator).toHaveAttribute('aria-valuenow', '62')
})

test('el umbral exacto de 800 px conserva el diseño adaptable sin separadores ocultos en la cuadrícula', async ({ page }) => {
  await page.setViewportSize({ width: 800, height: 800 })
  await page.goto('/app')
  await expect(page.getByRole('separator')).toHaveCount(0)
  await expect(page.locator('.elements-panel')).toBeHidden()
  await expect(page.locator('.canvas-panel')).toBeVisible()
  await expect(page.locator('.properties-panel')).toBeVisible()
  expect(await page.locator('.workspace').evaluate(element => (element as HTMLElement).style.gridTemplateColumns)).toBe('')
  await page.getByRole('button', { name: 'Inventario', exact: true }).click()
  await expect(page.getByRole('separator')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Plano de consulta' })).toBeVisible()
  expect(await page.locator('.operations-workspace').evaluate(element => getComputedStyle(element).display)).toBe('flex')
  await page.setViewportSize({ width: 1100, height: 740 })
  await expect(page.getByRole('separator')).toHaveCount(1)
  await page.getByRole('button', { name: 'Diseñar', exact: true }).click()
  await expect(page.getByRole('separator')).toHaveCount(2)
  await expect(page.locator('.elements-panel')).toBeVisible()
  await expect.poll(() => width(page.locator('.canvas-panel'))).toBeGreaterThanOrEqual(300)
})

